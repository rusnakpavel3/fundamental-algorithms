#ifndef STATUS_H
#define STATUS_H

typedef enum {
    STATUS_OK = 0,
    STATUS_ERR_NULL_ARGUMENT,
    STATUS_ERR_SUBSTRING_EMPTY,
    STATUS_ERR_COUNT_NEGATIVE,
    STATUS_ERR_SIZE_OVERFLOW,
    STATUS_ERR_ALLOC_FAILED,
    STATUS_ERR_PATH_NULL,
    STATUS_ERR_PATH_EMPTY,
    STATUS_ERR_FILE_OPEN_FAILED,
    STATUS_ERR_FILE_READ_FAILED,
    STATUS_ERR_FILE_TOO_LARGE
} Status;

const char *status_message(const Status status);

#endif
